#!/usr/bin/env python3
"""Generate the Fairy Builder icon: SVG master + Android adaptive-icon vector drawables.

One description of the art (below) feeds every output, so they cannot drift apart.

    python3 icon/make-icon.py          # writes SVG, drawables, and the 512px PNG

Canvas is the 108dp adaptive-icon canvas; all art stays inside the 66dp safe zone
(radius 33 around the centre).
"""
import pathlib
import shutil
import subprocess

HERE = pathlib.Path(__file__).resolve().parent
RES = HERE.parent / "android" / "builder" / "src" / "main" / "res"

# ---- palette -------------------------------------------------------------
BG_INNER = "#2E1F57"   # night-plum panel, centre
BG_OUTER = "#140C2B"   # panel edge
UNLIT = "#FFFFFF"      # unlit LED, drawn at UNLIT_ALPHA
UNLIT_ALPHA = 0.13
GHOST = "#8FA8FF"      # onion-skin of the previous frame
GHOST_ALPHA = 0.45
LIT_TOP = "#FF5C8A"    # lit LEDs: warm pink at the top ...
LIT_BOTTOM = "#FFC145"  # ... to amber at the bottom
GLOW = "#FF9A5C"       # soft halo behind the lit shape
MONO = "#FFFFFF"       # themed-icon layer (system tints it)

# ---- geometry ------------------------------------------------------------
C = 54.0      # canvas centre
N = 6         # 6 x 6 grid of LEDs: few, large dots survive at 48px
PITCH = 8.0
R_LIT = 3.5
R_GHOST = 3.0
R_UNLIT = 1.9
RING = 1.3    # ghost ring stroke in the monochrome layer

HEART = [
    "......",
    "..X.X.",
    ".XXXXX",
    ".XXXXX",
    "..XXX.",
    "...X..",
]
GHOST_SHIFT = (-1, -1)  # previous frame: one LED up and left


def pos(col, row):
    return C + (col - (N - 1) / 2) * PITCH, C + (row - (N - 1) / 2) * PITCH


lit = {(c, r) for r, line in enumerate(HEART) for c, ch in enumerate(line) if ch == "X"}
ghost = {(c + GHOST_SHIFT[0], r + GHOST_SHIFT[1]) for c, r in lit}
ghost = {(c, r) for c, r in ghost if 0 <= c < N and 0 <= r < N} - lit
unlit = {(c, r) for c in range(N) for r in range(N)} - lit - ghost

LIT_Y0 = min(pos(c, r)[1] for c, r in lit) - R_LIT
LIT_Y1 = max(pos(c, r)[1] for c, r in lit) + R_LIT
GLOW_C = (sum(pos(c, r)[0] for c, r in lit) / len(lit), (LIT_Y0 + LIT_Y1) / 2)
GLOW_R = 26.0


def safe_check():
    """Every shape must sit inside the 66dp safe circle."""
    def dist(x, y):
        return ((x - C) ** 2 + (y - C) ** 2) ** 0.5
    shapes = [(*pos(c, r), R_LIT) for c, r in lit]
    shapes += [(*pos(c, r), R_GHOST) for c, r in ghost]
    shapes += [(*pos(c, r), R_UNLIT) for c, r in unlit]
    shapes.append((*GLOW_C, GLOW_R))
    for x, y, rad in shapes:
        assert dist(x, y) + rad <= 33.0 + 1e-6, (x, y, rad)


def circles(cells, rad):
    out = []
    for c, r in sorted(cells, key=lambda t: (t[1], t[0])):
        x, y = pos(c, r)
        out.append(f"M{x - rad:g},{y:g}a{rad:g},{rad:g} 0 1,0 {2 * rad:g},0a{rad:g},{rad:g} 0 1,0 {-2 * rad:g},0Z")
    return "".join(out)


def argb(hex6, alpha=1.0):
    return f"#{round(alpha * 255):02X}{hex6[1:]}"


# ---- SVG master ----------------------------------------------------------
def svg():
    gx, gy = GLOW_C
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 108 108">
  <!-- Generated by make-icon.py; edit that, not this. -->
  <defs>
    <radialGradient id="bg" cx="54" cy="54" r="76" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{BG_INNER}"/><stop offset="1" stop-color="{BG_OUTER}"/>
    </radialGradient>
    <radialGradient id="glow" cx="{gx:g}" cy="{gy:g}" r="{GLOW_R:g}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{GLOW}" stop-opacity="0.55"/><stop offset="1" stop-color="{GLOW}" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="lit" x1="0" y1="{LIT_Y0:g}" x2="0" y2="{LIT_Y1:g}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{LIT_TOP}"/><stop offset="1" stop-color="{LIT_BOTTOM}"/>
    </linearGradient>
  </defs>
  <rect width="108" height="108" fill="url(#bg)"/>
  <circle cx="{gx:g}" cy="{gy:g}" r="{GLOW_R:g}" fill="url(#glow)"/>
  <path fill="{UNLIT}" fill-opacity="{UNLIT_ALPHA}" d="{circles(unlit, R_UNLIT)}"/>
  <path fill="{GHOST}" fill-opacity="{GHOST_ALPHA}" d="{circles(ghost, R_GHOST)}"/>
  <path fill="url(#lit)" d="{circles(lit, R_LIT)}"/>
</svg>
"""


def mono_svg():
    """Preview of the themed-icon layer, for checking only."""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 108 108">
  <rect width="108" height="108" fill="#2B3A35"/>
  <path fill="#CDEBE0" d="{mono_path()}"/>
</svg>
"""


def mono_path():
    # Lit LEDs solid, ghost LEDs as rings: one colour, no alpha. Unlit LEDs are
    # left out; at launcher size they only add noise.
    rings = []
    inner = R_GHOST - RING
    for c, r in sorted(ghost, key=lambda t: (t[1], t[0])):
        x, y = pos(c, r)
        # outer circle clockwise, inner counter-clockwise -> hole (nonzero rule)
        rings.append(
            f"M{x - R_GHOST:g},{y:g}a{R_GHOST:g},{R_GHOST:g} 0 1,0 {2 * R_GHOST:g},0a{R_GHOST:g},{R_GHOST:g} 0 1,0 {-2 * R_GHOST:g},0Z"
            f"M{x - inner:g},{y:g}a{inner:g},{inner:g} 0 1,1 {2 * inner:g},0a{inner:g},{inner:g} 0 1,1 {-2 * inner:g},0Z"
        )
    return circles(lit, R_LIT) + "".join(rings)


# ---- Android vector drawables -------------------------------------------
HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by icon/make-icon.py; edit that, not this. -->\n')
VEC = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"{extra}\n'
       '    android:width="108dp" android:height="108dp"\n'
       '    android:viewportWidth="108" android:viewportHeight="108">\n')
AAPT = '\n    xmlns:aapt="http://schemas.android.com/aapt"'


def background_xml():
    return HEAD + VEC.format(extra=AAPT) + f"""    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="54" android:centerY="54"
                android:gradientRadius="76"
                android:startColor="{BG_INNER}" android:endColor="{BG_OUTER}" />
        </aapt:attr>
    </path>
</vector>
"""


def foreground_xml():
    gx, gy = GLOW_C
    return HEAD + VEC.format(extra=AAPT) + f"""    <path android:pathData="M{gx - GLOW_R:g},{gy:g}a{GLOW_R:g},{GLOW_R:g} 0 1,0 {2 * GLOW_R:g},0a{GLOW_R:g},{GLOW_R:g} 0 1,0 {-2 * GLOW_R:g},0Z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="{gx:g}" android:centerY="{gy:g}"
                android:gradientRadius="{GLOW_R:g}"
                android:startColor="{argb(GLOW, 0.55)}" android:endColor="{argb(GLOW, 0)}" />
        </aapt:attr>
    </path>
    <path android:fillColor="{argb(UNLIT, UNLIT_ALPHA)}"
        android:pathData="{circles(unlit, R_UNLIT)}" />
    <path android:fillColor="{argb(GHOST, GHOST_ALPHA)}"
        android:pathData="{circles(ghost, R_GHOST)}" />
    <path android:pathData="{circles(lit, R_LIT)}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="54" android:startY="{LIT_Y0:g}"
                android:endX="54" android:endY="{LIT_Y1:g}"
                android:startColor="{LIT_TOP}" android:endColor="{LIT_BOTTOM}" />
        </aapt:attr>
    </path>
</vector>
"""


def monochrome_xml():
    return HEAD + VEC.format(extra="") + f"""    <path android:fillColor="{MONO}"
        android:pathData="{mono_path()}" />
</vector>
"""


ADAPTIVE = HEAD + """<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print("wrote", path)


def main():
    safe_check()
    write(HERE / "fairy-builder-icon.svg", svg())
    write(RES / "drawable" / "ic_launcher_background.xml", background_xml())
    write(RES / "drawable" / "ic_launcher_foreground.xml", foreground_xml())
    write(RES / "drawable" / "ic_launcher_monochrome.xml", monochrome_xml())
    write(RES / "mipmap-anydpi-v26" / "ic_launcher.xml", ADAPTIVE)
    write(RES / "mipmap-anydpi-v26" / "ic_launcher_round.xml", ADAPTIVE)
    if shutil.which("rsvg-convert"):
        png = HERE / "fairy-builder-icon-512.png"
        subprocess.run(["rsvg-convert", "-w", "512", "-h", "512", "-o", str(png),
                        str(HERE / "fairy-builder-icon.svg")], check=True)
        print("wrote", png)
    else:
        print("rsvg-convert not found; PNG not rendered")


if __name__ == "__main__":
    import sys
    if "--mono-preview" in sys.argv:
        sys.stdout.write(mono_svg())
    else:
        main()
